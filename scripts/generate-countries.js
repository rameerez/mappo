#!/usr/bin/env node
// Generates demo/countries.js — every country as fillable rings, keyed by ISO.
//
// WHY THIS IS IN demo/ AND NOT IN THE LIBRARY. mappo ships country BORDERS as
// one flat list of anonymous rings: enough to draw the lines, not enough to
// fill Brazil. A choropleth — the single most common thing anyone does with a
// world map in a dashboard — needs each country as its own closed shape with a
// name you can look it up by. The source data has that (Natural Earth admin-0
// carries ISO_A2, ISO_A3 and NAME on all 177 features) and the generator
// currently throws it away.
//
// So this file is a demonstration of a gap, not a workaround for one. If the
// shape below survives contact with the demo, it belongs in the earth pack as
// `regions()` beside `rings()` and `borders()`, and this script should be
// deleted rather than kept.
//
//   node scripts/generate-countries.js
//
// Same pinned commit and checksum the earth pack uses, so the outlines here
// cannot drift from the borders mappo draws underneath them.

import { writeFileSync } from "node:fs";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fetchCached } from "./lib/fetch.js";
import { simplifyRing, ringArea } from "./lib/geometry.js";
import { encodeRings, SCALE, ALPHABET } from "./lib/codec.js";

const here = dirname(fileURLToPath(import.meta.url));
const COMMIT = "ca96624a56bd078437bca8184e78163e5039ad19";
const SOURCE = {
  url: `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${COMMIT}/geojson/ne_110m_admin_0_countries.geojson`,
  sha256: "6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f",
  file: "ne_110m_admin_0_countries.geojson"
};

const EPSILON = 0.28;      // degrees; a fill tolerates far more than a coastline
const MIN_AREA = 0.35;     // deg², dropping specks — but never a country's last ring

const geo = JSON.parse(readFileSync(await fetchCached(SOURCE), "utf8"));

// ISO_A2 is "-99" for a handful of disputed or partially recognised places.
// Fall back rather than drop them: a map with a hole where Kosovo is looks
// like a bug, and the demo never needs to look them up by code.
const keyOf = (p) => {
  for (const k of [ p.ISO_A2, p.ISO_A2_EH, p.ISO_A3, p.ADM0_A3 ]) {
    if (k && k !== "-99" && k !== "-99.0") return String(k).toUpperCase();
  }
  return String(p.NAME || "??").toUpperCase().replace(/[^A-Z]/g, "").slice(0, 6);
};

const out = [];
for (const feature of geo.features) {
  const g = feature.geometry;
  if (!g) continue;
  const polygons = g.type === "Polygon" ? [ g.coordinates ]
    : g.type === "MultiPolygon" ? g.coordinates : [];

  const rings = [];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      // GeoJSON is [lon, lat]; everything downstream of here is [lat, lon].
      const latlon = ring.map(([ lon, lat ]) => [ lat, lon ]);
      const thin = simplifyRing(latlon, EPSILON);
      if (thin.length < 4) continue;
      rings.push({ ring: thin, area: Math.abs(ringArea(thin)) });
    }
  }
  if (!rings.length) continue;
  rings.sort((a, b) => b.area - a.area);
  // Everything above the floor, and always the largest — Singapore is a speck
  // and still has to be on the map.
  const kept = rings.filter((r, i) => i === 0 || r.area >= MIN_AREA).map((r) => r.ring);

  out.push({
    iso: keyOf(feature.properties),
    name: feature.properties.NAME_LONG || feature.properties.NAME,
    encoded: encodeRings(kept),
    rings: kept.length,
    points: kept.reduce((n, r) => n + r.length, 0)
  });
}

out.sort((a, b) => a.iso.localeCompare(b.iso));
const dupes = out.filter((c, i) => out.findIndex((o) => o.iso === c.iso) !== i);
if (dupes.length) throw new Error(`duplicate keys: ${dupes.map((d) => d.iso).join(", ")}`);

const body = out.map((c) => `  "${c.iso}": ["${c.name.replace(/"/g, '\\"')}","${c.encoded}"]`).join(",\n");
const source = `// GENERATED by scripts/generate-countries.js — do not edit by hand.
//
// Every country as closed [lat, lon] rings, keyed by ISO 3166-1 alpha-2, in
// the same 1/${SCALE}° delta+zigzag+varint encoding mappo uses for its own
// coastlines — so these fills register exactly with the borders drawn under
// them. Natural Earth admin-0 110m, public domain, pinned by checksum.
//
// This lives in demo/ because mappo does not ship it. See the header of
// scripts/generate-countries.js for what that means.

const RAW = {
${body}
};

const SCALE = ${SCALE};
const ALPHABET = "${ALPHABET}";

${decodeSource()}

const cache = new Map();

// Closed rings of [lat, lon] for one country, or null. Decoded on first ask
// and kept: a choropleth wants every country, a tooltip wants one.
export function countryRings(iso) {
  const key = String(iso || "").toUpperCase();
  if (cache.has(key)) return cache.get(key);
  const entry = RAW[key];
  const rings = entry ? decodeRings(entry[1], SCALE, ALPHABET) : null;
  cache.set(key, rings);
  return rings;
}

export const countryName = (iso) => RAW[String(iso || "").toUpperCase()]?.[0] ?? null;
export const countryCodes = () => Object.keys(RAW);
`;

// The decoder travels with the data, exactly as a body pack's does, so this
// file stays standalone and cannot drift from the codec it was written with.
function decodeSource() {
  const src = readFileSync(join(here, "lib", "codec.js"), "utf8");
  const start = src.indexOf("export function decodeRings");
  if (start < 0) throw new Error("codec.js: decodeRings not found");
  let depth = 0, i = src.indexOf("{", start);
  const from = i;
  do { if (src[i] === "{") depth++; else if (src[i] === "}") depth--; i++; } while (depth > 0);
  return "function decodeRings" + src.slice(src.indexOf("(", start), from) + src.slice(from, i);
}

writeFileSync(join(here, "..", "demo", "countries.js"), source);
console.log(`${out.length} countries, ${out.reduce((n, c) => n + c.rings, 0)} rings, ` +
  `${out.reduce((n, c) => n + c.points, 0)} points`);
console.log(`wrote demo/countries.js`);
